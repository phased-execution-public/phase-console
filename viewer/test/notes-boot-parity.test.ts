test('the section parser reads every spelling of an address and refuses the rest', () => {
  const rows = parseNoteSection([
    '## Notes for later phases',
    '',
    '- **Phase 7:** bold and addressed',
    '- **For phase 8:** the other spelling',
    '* Phase 9: no emphasis at all',
    '- **NEXT:** case does not matter',
    '- **All:** everybody',
    '- **Outstanding:** a label that is not an address',
    '- no colon at all',
    '',
    '## Outstanding / blockers',
    '- **Phase 7:** outside the section entirely',
  ].join('\n'));
  assert.deepEqual(rows, [
    { target: '7', text: 'bold and addressed' },
    { target: '8', text: 'the other spelling' },
    { target: '9', text: 'no emphasis at all' },
    { target: 'next', text: 'case does not matter' },
    { target: 'all', text: 'everybody' },
  ]);
});

test('noteReaches never hands a phase its own note, whatever the address', () => {
  for (const target of ['4', 'next', 'all']) {
    assert.equal(noteReaches(target, 4, 4, [2, 3]), false, target);
  }
  assert.equal(noteReaches('next', 2, 4, [2, 3]), true);
  assert.equal(noteReaches('next', 1, 4, [2, 3]), false, 'next is a dependency edge, not a phase number');
  assert.equal(noteReaches('all', 1, 4, [2, 3]), true);
});
